import {readFileSync,writeFileSync} from 'node:fs';
import solc from 'solc';
import {JsonRpcProvider,Wallet,ContractFactory,keccak256} from 'ethers';
const provider=new JsonRpcProvider('https://testnet-rpc.monad.xyz');
if((await provider.getNetwork()).chainId!==10143n)throw Error('Wrong chain');
const wallet=new Wallet(JSON.parse(readFileSync('.local-secrets/monad-testnet-wallet.json')).privateKey,provider);
const source=readFileSync('onchain/EvidenceAnchor.sol','utf8');
const input={language:'Solidity',sources:{'EvidenceAnchor.sol':{content:source}},settings:{evmVersion:'paris',optimizer:{enabled:true,runs:200},outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}};
const output=JSON.parse(solc.compile(JSON.stringify(input)));
if(output.errors?.some(e=>e.severity==='error'))throw Error(JSON.stringify(output.errors));
const c=output.contracts['EvidenceAnchor.sol'].EvidenceAnchor;
const factory=new ContractFactory(c.abi,c.evm.bytecode.object,wallet);
const tx=await factory.getDeployTransaction();
console.log('Estimated deployment gas:',String(await provider.estimateGas({...tx,from:wallet.address})));
const contract=await factory.deploy();
console.log('Deployment transaction:',contract.deploymentTransaction().hash);
const receipt=await contract.deploymentTransaction().wait();
if(receipt.status!==1)throw Error('Deployment failed');
const address=await contract.getAddress();
const code=await provider.getCode(address);if(code==='0x')throw Error('No code');
const result={chainId:10143,rpc:'https://testnet-rpc.monad.xyz',address,owner:wallet.address,transactionHash:receipt.hash,blockNumber:receipt.blockNumber,status:receipt.status,compiler:solc.version(),evmVersion:'paris',runtimeCodeHash:keccak256(code),deployedAt:new Date().toISOString()};
writeFileSync('onchain/deployments/monad-testnet.json',JSON.stringify(result,null,2)+'\n');
writeFileSync('onchain/build/EvidenceAnchor.abi',JSON.stringify(c.abi,null,2)+'\n');
writeFileSync('onchain/build/EvidenceAnchor.bin',c.evm.bytecode.object+'\n');
console.log(JSON.stringify(result,null,2));
